"""Typed views of the JSON the listener writes (schema_version 1).

The listener is the writer; these classes only read. Fixtures in tests/fixtures are generated by
the listener's own writer code (listener/tests/test_contract.py), so the two can't drift.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Any

SCHEMA_VERSION = 1


def _ts(s: str) -> datetime:
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def _check_schema(d: dict[str, Any], what: str) -> None:
    v = d.get("schema_version")
    if v != SCHEMA_VERSION:
        raise ValueError(f"{what}: unsupported schema_version {v!r} (expected {SCHEMA_VERSION})")


@dataclass(frozen=True)
class Window:
    start: datetime
    end: datetime
    confidence: float
    loudness_dbfs: float


@dataclass(frozen=True)
class Gap:
    start: datetime
    end: datetime
    seconds: float


@dataclass(frozen=True)
class EpisodeMeta:
    episode_id: str
    start: datetime
    end: datetime
    clip_start: datetime
    clip_end: datetime
    barking_seconds: float
    bursts: int
    longest_gap_seconds: float
    mean_loudness_dbfs: float
    merged_from: int
    windows: tuple[Window, ...]
    device: str
    model: str
    confidence_threshold: float
    sample_rate: int
    duration_seconds: float
    flac_sha256: str
    complete: bool
    gaps: tuple[Gap, ...]
    timezone: str
    clock_source: str

    @property
    def duration(self) -> float:
        return (self.end - self.start).total_seconds()

    @classmethod
    def from_json(cls, d: dict[str, Any]) -> EpisodeMeta:
        _check_schema(d, "episode metadata")
        audio = d["audio"]
        clock = d.get("clock") or {}
        return cls(
            episode_id=d["episode_id"],
            start=_ts(d["start"]),
            end=_ts(d["end"]),
            clip_start=_ts(d["clip_start"]),
            clip_end=_ts(d["clip_end"]),
            barking_seconds=float(d["barking_seconds"]),
            bursts=int(d.get("barking_bursts_estimated", d.get("bark_count_estimated", 0))),
            longest_gap_seconds=float(d["longest_gap_seconds"]),
            mean_loudness_dbfs=float(d["mean_loudness_dbfs"]),
            merged_from=int(d["merged_from"]),
            windows=tuple(
                Window(_ts(w["start"]), _ts(w["end"]), w["confidence"], w["loudness_dbfs"])
                for w in d["windows"]
            ),
            device=d["device"],
            model=d["detector"]["model"],
            confidence_threshold=float(d["detector"]["confidence_threshold"]),
            sample_rate=int(audio["sample_rate"]),
            duration_seconds=float(audio["duration_seconds"]),
            flac_sha256=audio["sha256"],
            complete=bool(audio.get("complete", True)),
            gaps=tuple(
                Gap(_ts(g["start"]), _ts(g["end"]), float(g["seconds"]))
                for g in audio.get("gaps", [])
            ),
            timezone=clock.get("timezone", "UTC"),
            clock_source=clock.get("source", "unknown"),
        )


@dataclass(frozen=True)
class Rule:
    name: str
    confidence_threshold: float
    episode_min_minutes: float
    max_gap_seconds: float
    min_separation_minutes: float
    episodes_per_window: int
    violation_window_hours: float
    citation: str
    caveat: str
    addressee: str


@dataclass(frozen=True)
class Manifest:
    violation_id: str
    revision: int
    window_start: datetime
    window_end: datetime
    episode_ids: tuple[str, ...]
    rule: Rule
    hourly_history: tuple[tuple[datetime, int], ...]

    @classmethod
    def from_json(cls, d: dict[str, Any]) -> Manifest:
        _check_schema(d, "violation manifest")
        r = d["rule"]
        return cls(
            violation_id=d["violation_id"],
            revision=int(d["revision"]),
            window_start=_ts(d["window_start"]),
            window_end=_ts(d["window_end"]),
            episode_ids=tuple(d["episode_ids"]),
            rule=Rule(
                name=r["name"],
                confidence_threshold=float(r["confidence_threshold"]),
                episode_min_minutes=float(r["episode_min_minutes"]),
                max_gap_seconds=float(r["max_gap_seconds"]),
                min_separation_minutes=float(r["min_separation_minutes"]),
                episodes_per_window=int(r["episodes_per_window"]),
                violation_window_hours=float(r["violation_window_hours"]),
                citation=r["citation"],
                caveat=r["caveat"],
                addressee=r["addressee"],
            ),
            hourly_history=tuple(
                (_ts(h["hour_start"]), int(h["barks"])) for h in d["hourly_history"]
            ),
        )
